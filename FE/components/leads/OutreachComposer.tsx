"use client";

import { useState } from "react";
import { Lead } from "@/types/lead";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { getEmailPreview } from "@/services/leads.service";
import { useToast } from "@/components/ui/toast";

export function OutreachComposer({ lead }: { lead: Lead }) {
  const [recipientEmail, setRecipientEmail] = useState("");
  const [recipientName, setRecipientName] = useState("");
  const [draft, setDraft] = useState<{ subject: string; body: string; profile: string; source: string; verification?: { status: string } | null } | null>(null);
  const [loading, setLoading] = useState(false);
  const [message, setMessage] = useState("");
  const { toast } = useToast();

  async function preview() {
    setLoading(true); setMessage("");
    try { setDraft((await getEmailPreview(lead.id, { recipientEmail: recipientEmail || undefined, recipientName: recipientName || undefined })).data); toast({ variant: "success", title: "Preview generated", description: "Review the message before using it in a campaign." }); }
    catch (error) { setMessage(error instanceof Error ? error.message : "Unable to create email preview"); }
    finally { setLoading(false); }
  }

  return <Card>
    <CardHeader><CardTitle>Personalized outreach</CardTitle></CardHeader>
    <CardContent className="space-y-3">
      <div className="grid md:grid-cols-2 gap-3">
        <input className="border rounded-md px-3 py-2 text-sm" placeholder="Recipient name (optional)" value={recipientName} onChange={(e) => setRecipientName(e.target.value)} />
        <input className="border rounded-md px-3 py-2 text-sm" type="email" placeholder="Recipient email" value={recipientEmail} onChange={(e) => setRecipientEmail(e.target.value)} />
      </div>
      <div className="flex flex-wrap items-center gap-2"><Button type="button" variant="outline" onClick={preview} disabled={loading}>{loading ? "Working..." : "Preview email"}</Button><p className="text-xs text-muted-foreground">Sending is controlled by approved campaigns.</p></div>
      {draft && <div className="rounded-md border bg-muted/30 p-4 space-y-2"><p className="text-xs text-muted-foreground">Profile: {draft.profile} · Generated by: {draft.source}</p><p className="font-medium">{draft.subject}</p><textarea className="w-full min-h-40 rounded-md border bg-background p-3 text-sm" value={draft.body} onChange={(e) => setDraft({ ...draft, body: e.target.value })} /></div>}
      {message && <p className="text-sm text-muted-foreground">{message}</p>}
    </CardContent>
  </Card>;
}
